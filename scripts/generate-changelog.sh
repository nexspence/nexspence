#!/usr/bin/env bash
# generate-changelog.sh — regenerates CHANGELOG.md from the GitHub releases.
#
# The release notes are written once, when the release is cut, and they are the
# single source of truth. This script collects them into a file that lives in the
# repository, so that "when did X land?" is answerable without a browser — and
# so that the changelog is searchable from the repository itself.
#
# Usage:
#   ./scripts/generate-changelog.sh
#   REPO=nexspence/nexspence OUT=/tmp/CHANGELOG.md ./scripts/generate-changelog.sh
#
# Environment variables:
#   REPO — owner/name of the repository          (default: nexspence/nexspence)
#   OUT  — path of the file to write              (default: CHANGELOG.md)
#
# Requires the GitHub CLI (`gh`) with read access to the repository. Run it
# after cutting a release, before announcing it.
set -euo pipefail

REPO="${REPO:-nexspence/nexspence}"
OUT="${OUT:-CHANGELOG.md}"

if ! command -v gh >/dev/null 2>&1; then
    echo "error: the GitHub CLI (gh) is required" >&2
    exit 1
fi

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
    echo "# Changelog"
    echo
    echo "<!-- Generated by scripts/generate-changelog.sh — do not edit by hand. -->"
    echo
    echo "All notable changes to Nexspence, newest first. The release notes are written"
    echo "when the release is cut; this file collects them."
    echo
    echo "The full release notes — including the Docker image matrix and the"
    echo "essentials bundle — are on the [releases page](https://github.com/$REPO/releases)."
    echo
} >"$tmp"

# gh's --jq runs gojq, so no jq binary is needed. Drafts are skipped, and the
# "## Changelog" heading the release notes start with is dropped — this file
# already provides the structure.
gh api --paginate "repos/$REPO/releases?per_page=100" \
    --jq '.[] | select(.draft == false) |
           "## \(.tag_name)\n\n\(.published_at[0:10]) — \(.name // .tag_name)\n\n\((.body // "") | sub("^## Changelog\n+"; ""))\n\n---\n\n"' \
    >>"$tmp"

releases="$(grep -c '^## v' "$tmp" || true)"

{
    cat "$tmp"
} >"$OUT"

echo "Wrote $OUT — $releases releases."
